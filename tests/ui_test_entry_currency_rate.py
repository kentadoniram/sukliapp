from playwright.sync_api import sync_playwright
import pkhelp; pkhelp.patch()
import json, re
S='/tmp/claude-0/-home-claude/e0191d68-b6bd-5145-8d10-9c3cd7e19bda/scratchpad/'
CSV='/mnt/user-data/uploads/Transactions.csv'
errs=[]; res=[]
def ok(n,c): res.append(bool(c)); print(('PASS ' if c else 'FAIL ')+n)
with sync_playwright() as p:
    b=p.chromium.launch()
    ctx=b.new_context(viewport={'width':390,'height':844},device_scale_factor=2,locale='en-US',timezone_id='Asia/Tokyo',service_workers='block')
    pg=ctx.new_page()
    pg.on('console',lambda m: errs.append(m.text) if m.type=='error' else None)
    pg.on('pageerror',lambda e: errs.append(str(e)))
    pg.goto('http://localhost:8123/index.html'); pg.wait_for_selector('#first-file',state='attached')
    pg.set_input_files('#first-file',CSV); pg.wait_for_selector('#setup',timeout=20000); pg.click('#setup .btn'); pg.wait_for_timeout(500)
    # ---- 5 currency selector on the amount ----
    pg.click('.fab'); pg.wait_for_selector('#entry')
    curs=pg.eval_on_selector_all('#f-cur option','os=>os.map(o=>o.value)'); print('  currencies',curs)
    ok('currency selector inside amount box', pg.locator('.amtrow #f-cur').count()==1 and 'PHP' in curs and 'JPY' in curs)
    pg.select_option('#f-cur','JPY'); pg.wait_for_timeout(150)
    accs=pg.eval_on_selector_all('#f-acct option:checked','os=>os.map(o=>o.textContent)')
    ok('choosing a currency selects an account in that currency', accs and all('JPY' in a for a in accs))
    ok('exchange line appears for yen', pg.locator('#f-fx').count()==1)
    pg.select_option('#f-cur','PHP'); pg.wait_for_timeout(150)
    ok('back to PHP hides the rate line', pg.locator('#f-fx').count()==0)
    # ---- 14 calculator ----
    pg.fill('#f-amount','120+45*2'); pg.dispatch_event('#f-amount','input'); pg.wait_for_timeout(100)
    ok('live result shows = ₱210.00: '+pg.inner_text('#calcres'), '210.00' in pg.inner_text('#calcres'))
    pg.click('.calcbtn'); pg.wait_for_timeout(100)
    ok('keypad opens, phone keyboard suppressed', pg.locator('#keypad button').count()==20 and pg.get_attribute('#f-amount','inputmode')=='none')
    pg.click('#keypad [data-v="C"]')
    for k in ['1','2','0','×','3','+','5','=']: pg.click(f'#keypad [data-v="{k}"]')
    ok('keypad 120×3+5 = 365: '+pg.input_value('#f-amount'), pg.input_value('#f-amount')=='365')
    pg.click('.calcbtn'); pg.fill('#f-amount','100+20%'); pg.dispatch_event('#f-amount','input')
    pg.evaluate("document.querySelector('#f-amount').blur()"); pg.dispatch_event('#f-amount','focusout'); pg.wait_for_timeout(100)
    ok('expression collapses to result on leaving the box: '+pg.input_value('#f-amount'), pg.input_value('#f-amount')=='120')
    pg.screenshot(path=S+'v5-entry.png')
    # ---- 6 category follows each letter ----
    pg.fill('#f-what',''); pg.dispatch_event('#f-what','input')
    pg.fill('#f-what','g'); pg.dispatch_event('#f-what','input'); pg.wait_for_timeout(150)
    c1=pg.locator('#catrow .chip.cat').all_inner_texts()
    pg.fill('#f-what','gro'); pg.dispatch_event('#f-what','input'); pg.wait_for_timeout(150)
    c2=pg.locator('#catrow .chip.cat').all_inner_texts()
    print('  g ->',c1,' gro ->',c2)
    ok('chips change as letters are typed', c1!=c2 and any('Grocer' in x for x in c2))
    pg.fill('#f-what','zqxw'); pg.dispatch_event('#f-what','input'); pg.wait_for_timeout(150)
    ok('no fit shows add-category option', pg.locator('.nofit').count()==1)
    pg.click('.nofit'); pg.wait_for_selector('#catform')
    ok('new-category form prefilled', pg.input_value('#catform [name=n]').lower().startswith('zqxw') and 'zqxw' in pg.input_value('#catform [name=k]'))
    pg.fill('#catform [name=g]','Test group'); pg.click('#catform .btn:not([data-del])'); pg.wait_for_timeout(200)
    ok('after adding, it is selected', pg.locator('#catrow .chip.cat.on').count()==1 and 'Zqxw' in pg.inner_text('#catrow .chip.cat.on'))
    pg.click('[data-close]')
    # ---- 12 transfer fee ----
    pg.click('.fab'); pg.wait_for_selector('#entry'); pg.click('[data-e=kind][data-v=transfer]'); pg.wait_for_timeout(150)
    ok('fee control on transfer: 0 Fee by default, amount row hidden', pg.locator('[data-e=feemode]').count()==3 and pg.locator('#f-fee').count()==0 and pg.locator('[data-e=feemode][data-v=none].on').count()==1)
    pg.click('[data-e=feemode][data-v=fixed]'); pg.wait_for_timeout(100)
    ok('Fixed Amount opens fee amount and Maker/Taker', pg.locator('#f-fee').count()==1 and pg.locator('[data-e=feeby]').count()==2)
    pg.select_option('#f-cur','PHP'); pg.wait_for_timeout(100)
    frm=pg.input_value('#f-acct')
    opts=pg.eval_on_selector_all('#f-to option','os=>os.map(o=>[o.value,o.textContent])'); to=[o[0] for o in opts if 'PHP' in o[1] and o[0]!=frm][0]
    pg.select_option('#f-to',to); pg.wait_for_timeout(100)
    pg.fill('#f-amount','5000'); pg.dispatch_event('#f-amount','input')
    pg.fill('#f-fee','25'); pg.dispatch_event('#f-fee','input')
    pg.select_option('#f-feecat','__new:Bank service fee'); pg.wait_for_timeout(100)
    pg.click('[data-e=feeby][data-v=to]'); pg.wait_for_timeout(100)
    ok('fee type kept after re-render', pg.input_value('#f-feecat')=='__new:Bank service fee' and pg.input_value('#f-fee')=='25')
    before=pg.evaluate("(()=>{const m=window.sukli.balancesNow();return Object.fromEntries(m)})()")
    pg.click('[data-e=save]'); pg.wait_for_timeout(300)
    after=pg.evaluate("(()=>{const m=window.sukli.balancesNow();return Object.fromEntries(m)})()")
    ok('sender -5000, receiver +4975 (fee from receiver)', abs(after[frm]-before[frm]+5000)<0.01 and abs(after[to]-before[to]-4975)<0.01)
    tx=pg.evaluate("window.sukli.get().txs.filter(t=>t.fee>0).pop()")
    cat=pg.evaluate("(id)=>window.sukli.get().categories.find(c=>c.id===id)", tx['feeCat'])
    ok('fee category created under Fees: '+str(cat and cat['group']+'/'+cat['name']), cat and cat['group']=='Fees' and cat['name']=='Bank service fee')
    # prediction on a second transfer of the same route
    pg.click('.fab'); pg.wait_for_selector('#entry'); pg.click('[data-e=kind][data-v=transfer]'); pg.wait_for_timeout(100)
    pg.select_option('#f-acct',frm); pg.wait_for_timeout(100); pg.select_option('#f-to',to); pg.wait_for_timeout(150)
    ok('fee predicted from history: '+pg.input_value('#f-fee'), pg.input_value('#f-fee')=='25' and pg.locator('.feebox.suggested').count()==1)
    pg.click('[data-close]')
    print('errors:',errs)
    ok('no console errors', not [e for e in errs if 'TUNNEL' not in e])
    b.close()
print(sum(res),'/',len(res)); 
