from playwright.sync_api import sync_playwright
CSV='/home/claude/Transactions.csv'
errs=[]; res=[]
def ok(n,c): res.append(bool(c)); print(('PASS ' if c else 'FAIL ')+n)
def pick(ids):
    c=pg.evaluate(f"window.sukli.get().accounts.find(a=>a.id==='{ids[0]}').cur")
    pg.select_option('#f-cur',c); pg.wait_for_timeout(200)
    pg.select_option('#f-acct',ids[0]); pg.select_option('#f-to',ids[1]); pg.wait_for_timeout(200)
with sync_playwright() as p:
    b=p.chromium.launch(); ctx=b.new_context(viewport={'width':390,'height':844},locale='en-US',service_workers='block'); pg=ctx.new_page(); globals()['pg']=pg
    pg.on('pageerror',lambda e: errs.append(str(e)))
    pg.goto('http://localhost:8123/index.html'); pg.wait_for_selector('#first-file',state='attached')
    pg.set_input_files('#first-file',CSV); pg.wait_for_selector('#setup',timeout=20000); pg.click('#setup .btn'); pg.wait_for_timeout(600)
    pg.evaluate("window.sukli.commit(d=>{d.settings.safety={on:true,mode:'rolling',limit:1000,warnPct:80,cardPct:50,essentials:[]}})")
    pg.evaluate("document.querySelector('[data-act=add]').click()"); pg.wait_for_selector('#entry')
    pg.fill('#f-amount','5000'); pg.wait_for_timeout(500)
    t=pg.inner_text('#safety'); print(t[:200])
    ok('limit warning appears for big expense', 'limit' in t.lower() or 'income' in t.lower())
    pg.fill('#f-amount','1'); pg.wait_for_timeout(500)
    print(pg.inner_text('#safety')[:200])
    # multi-currency transfer with optional conversion
    cur=pg.evaluate("[...new Set(window.sukli.get().accounts.filter(a=>!a.deleted).map(a=>a.cur))]"); print(cur)
    pg.click('[data-e="kind"][data-v="transfer"]')
    ids=pg.evaluate("(()=>{const a=window.sukli.get().accounts.filter(x=>!x.deleted&&!x.archived);const x=a.find(q=>q.cur==='USDT')||a.find(q=>q.cur!=='PHP');const y=a.find(q=>q.cur==='PHP');return [x&&x.id,y&&y.id]})()")
    pick(ids)
    ok('conversion checkbox shown, off by default', pg.locator('#f-conv').count()==1 and pg.locator('#f-conv:checked').count()==0)
    pg.fill('#f-amount','100'); pg.fill('#f-name','xfer test')
    if pg.locator('#f-fx').count() and not pg.input_value('#f-fx'): pg.click('[data-e=fxopen]'); pg.fill('#cv-r','58'); pg.dispatch_event('#cv-r','input'); pg.click('#cv-apply'); pg.wait_for_timeout(100)
    pg.click('[data-e="save"]'); pg.wait_for_timeout(500)
    print('ERRBOX:',pg.evaluate("(document.querySelector('#err')||{}).textContent"), pg.evaluate("(document.querySelector('#f-fee')||{}).value"))
    tx=pg.evaluate("window.sukli.get().txs.find(t=>t.name==='xfer test')")
    ok('same number arrives when conversion off', tx and tx['toAmount']==100)
    pg.evaluate("document.querySelector('[data-act=add]').click()"); pg.wait_for_selector('#entry')
    pg.click('[data-e="kind"][data-v="transfer"]')
    pick(ids); pg.check('#f-conv'); pg.wait_for_timeout(200)
    pg.fill('#f-amount','100'); pg.fill('#f-toamt','5800')
    if pg.locator('#f-fx').count() and not pg.input_value('#f-fx'): pg.click('[data-e=fxopen]'); pg.fill('#cv-r','58'); pg.dispatch_event('#cv-r','input'); pg.click('#cv-apply'); pg.wait_for_timeout(100)
    pg.fill('#f-name','xfer conv'); pg.click('[data-e="save"]'); pg.wait_for_timeout(1000)
    tx=pg.evaluate("window.sukli.get().txs.find(t=>t.name==='xfer conv')")
    print('STATE',pg.locator('.scrim').count(), pg.evaluate("[...document.querySelectorAll('#err')].map(e=>e.textContent+e.hidden)"), pg.evaluate("document.querySelector('#f-conv')&&document.querySelector('#f-conv').checked"), pg.evaluate("document.querySelector('#f-toamt')&&document.querySelector('#f-toamt').value"))
    print('TX',pg.evaluate("window.sukli.get().txs.filter(t=>t.kind==='transfer').sort((a,b)=>b.updatedAt-a.updatedAt).slice(0,2).map(t=>[t.name,t.amount,t.toAmount,t.cur,t.acct,t.toAcct])"), pg.evaluate("(document.querySelector('#err')||{}).textContent"))
    ok('converted amount saved', tx and tx['toAmount']==5800)
    b.close()
print('ERRORS',errs); print(sum(res),'/',len(res))
