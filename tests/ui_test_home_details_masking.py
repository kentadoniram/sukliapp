from playwright.sync_api import sync_playwright
S='/tmp/claude-0/-home-claude/e0191d68-b6bd-5145-8d10-9c3cd7e19bda/scratchpad/'
CSV='/mnt/user-data/uploads/Transactions.csv'
errs=[]; ok=lambda n,c: print(('PASS ' if c else 'FAIL ')+n)
with sync_playwright() as p:
    b=p.chromium.launch()
    ctx=b.new_context(viewport={'width':390,'height':844},device_scale_factor=2,locale='en-US',timezone_id='Asia/Tokyo',service_workers='block')
    pg=ctx.new_page()
    pg.on('console',lambda m: errs.append(m.text) if m.type=='error' else None)
    pg.on('pageerror',lambda e: errs.append(str(e)))
    pg.goto('http://localhost:8123/index.html'); pg.wait_for_selector('#first-file',state='attached')
    pg.set_input_files('#first-file',CSV); pg.wait_for_selector('#setup',timeout=20000)
    pg.click('#setup .btn'); pg.wait_for_timeout(400)
    # 5 home analysis
    h=pg.inner_text('#view')
    for k in ['Worth knowing','Pace','Where it went','Where it came from','Last 6 months','Latest']:
        ok('home has '+k, k.lower() in h.lower() or (k=='Worth knowing' and pg.locator('.ins').count()>=0))
    print('insights:',pg.locator('.ins li').all_inner_texts())
    pg.screenshot(path=S+'v3-home.png',full_page=True)
    # 1 click group
    pg.locator('.gbar.click').first.click(); pg.wait_for_selector('#gd .gdhead')
    print('detail:',pg.inner_text('#gd .gdhead').replace('\n',' | '))
    pg.screenshot(path=S+'v3-detail.png')
    n0=pg.locator('#gd .prow').count()
    pg.locator('#gd .cbar').first.click(); pg.wait_for_timeout(100)
    n1=pg.locator('#gd .prow').count(); ok(f'category filter narrows list {n0}->{n1}', 0<n1<=n0)
    pg.locator('#gd .prow').first.click(); pg.wait_for_selector('#entry')
    ok('entry opens from detail', pg.locator('#f-amount').count()==1)
    pg.click('[data-close]'); pg.wait_for_timeout(100)
    # income detail (September has none, go back a month)
    pg.click('[data-act=month][data-d="-1"]'); pg.wait_for_timeout(300)
    pg.screenshot(path=S+'v3-home-prev.png',full_page=True)
    pg.locator('.gbar.click[data-k=income]').first.click(); pg.wait_for_selector('#gd .gdhead')
    ok('income detail opens', '%' in pg.inner_text('#gd .gdhead'))
    pg.screenshot(path=S+'v3-income-detail.png'); pg.click('[data-close]')
    # 4 eye
    before=pg.inner_text('.strip')
    pg.click('header [data-act=eye]'); pg.wait_for_timeout(200)
    hid=pg.inner_text('.strip'); ok('eye masks amounts: '+hid.replace('\n',' '), '•••' in hid and not any(c.isdigit() for c in hid))
    ok('mask also on spendable+bars', '•••' in pg.inner_text('.spendable') and '•••' in pg.inner_text('.gbar'))
    pg.screenshot(path=S+'v3-hidden.png')
    pg.reload(); pg.wait_for_selector('.strip'); ok('hidden state remembered after reload','•••' in pg.inner_text('.strip'))
    # entry sheet under hide: amount typed is masked
    pg.click('.fab'); pg.wait_for_selector('#entry'); pg.fill('#f-amount','1234')
    sec=pg.evaluate("getComputedStyle(document.querySelector('#f-amount')).webkitTextSecurity")
    ok('amount field masked while hidden ('+str(sec)+')', sec=='disc')
    pg.screenshot(path=S+'v3-entry-hidden.png')
    pg.click('.eye'); ok('entry eye shows again', 'Hide' in pg.inner_text('.eye'))
    # 6 yen equivalent
    pg.select_option('#f-acct', index=0)
    opts=pg.eval_on_selector_all('#f-acct option','os=>os.map(o=>[o.value,o.textContent])')
    yen=[o for o in opts if 'JPY' in o[1]][0]
    pg.select_option('#f-acct', yen[0]); pg.fill('#f-amount','1200'); pg.wait_for_timeout(150)
    eqv=pg.input_value('#f-peso'); ok('yen entry shows peso equivalent: '+eqv, float(eqv)>0)
    pg.screenshot(path=S+'v3-yen-entry.png')
    # 2 new spending category with keywords, predicted for unseen name
    pg.click('[data-e=newcat]'); pg.wait_for_selector('#catform')
    pg.fill('[name=g]','Health'); pg.fill('[name=n]','Gym'); pg.fill('[name=k]','gym, fitness, anytime'); pg.click('#catform .btn')
    pg.wait_for_timeout(200)
    ok('new category selected in entry', 'Gym' in pg.inner_text('#catrow .chip.on'))
    pg.click('[data-close]')
    pg.click('.fab'); pg.wait_for_selector('#entry'); pg.fill('#f-what','Anytime Fitness monthly'); pg.fill('#f-amount','3000'); pg.wait_for_timeout(200)
    on=pg.inner_text('#catrow .chip.on'); ok('unseen name predicted to new category: '+on, 'Gym' in on)
    pg.click('[data-e=save]'); pg.wait_for_timeout(300)
    # 3 income category with prediction
    pg.click('.fab'); pg.wait_for_selector('#entry'); pg.click('[data-e=kind][data-v=income]')
    pg.click('[data-e=newcat]'); pg.wait_for_selector('#catform')
    pg.fill('[name=g]','Side income'); pg.fill('[name=n]','Freelance'); pg.fill('[name=k]','freelance, commission'); pg.click('#catform .btn'); pg.wait_for_timeout(200)
    ok('income category created+selected', 'Freelance' in pg.inner_text('#catrow .chip.on'))
    pg.click('[data-close]')
    pg.click('.fab'); pg.wait_for_selector('#entry'); pg.click('[data-e=kind][data-v=income]'); pg.fill('#f-what','Logo commission'); pg.fill('#f-amount','5000'); pg.wait_for_timeout(200)
    on=pg.inner_text('#catrow .chip.on'); ok('income name predicted: '+on, 'Freelance' in on)
    pg.screenshot(path=S+'v3-income-entry.png')
    pg.click('[data-e=save]'); pg.wait_for_timeout(300)
    # manager
    pg.click('header [data-act=eye]') if '•••' in pg.inner_text('.strip') else None
    pg.goto('http://localhost:8123/index.html#/categories?k=income'); pg.wait_for_selector('[data-act=cat-new]')
    ok('manager lists Freelance', 'Freelance' in pg.inner_text('#view'))
    pg.screenshot(path=S+'v3-manager.png')
    pg.click('[data-act=cat-ren][data-g="Side income"]'); pg.wait_for_selector('form input[name=v]'); pg.fill('form input[name=v]','Gigs'); pg.keyboard.press('Enter'); pg.wait_for_timeout(200)
    ok('group renamed', 'Gigs' in pg.inner_text('#view') and 'Side income' not in pg.inner_text('#view'))
    pg.goto('http://localhost:8123/index.html#/settings'); pg.wait_for_selector('#showhome', state='attached'); pg.evaluate("document.querySelectorAll('details.sgroup,details.ssub').forEach(d=>d.open=true)"); pg.wait_for_timeout(150); pg.uncheck('#showhome'); pg.wait_for_timeout(200)
    pg.goto('http://localhost:8123/index.html#/accounts'); pg.wait_for_selector('.row.acct')
    ok('equivalents hidden when toggled off', '≈' not in pg.inner_text('#view'))
    print('ERRORS:',errs)
    b.close()
